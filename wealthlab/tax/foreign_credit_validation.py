"""Validate observed identities, dates and opening ownership before tax calculations.

Each filing role has one stable person. Native amounts retain an explicit
spot quote, including historical records needed to identify a later refund.
Opening carry vintages keep their source year and cannot already belong to
the current year. Supplied baseline credits are excluded before this bridge
generates its own claim, preventing duplicate tax benefits.
"""


def validate(case):
    if case.as_of.year != case.annual.policy.year:
        raise ValueError("Credit observation year must equal the federal annual year.")
    roles = list(case.people.values())
    required = {"primary", "spouse"} if case.annual.filing.status == "joint" else {"primary"}
    if set(roles) != required or len(set(roles)) != len(roles):
        raise ValueError("Each annual filing role needs exactly one stable person identity.")
    identities = [r.id for r in [*case.income, *case.tax_cash, *case.opening_carries]]
    if len(identities) != len(set(identities)):
        raise ValueError("Income, tax-cash and carry identities must be globally unique.")
    validate_records(case)


def validate_records(case):
    for row in [*case.income, *case.tax_cash, *case.opening_carries]:
        if row.owner_id not in case.people:
            raise ValueError("Each source/payment/carry must identify a known filing-unit person.")
    validate_values(case)
    validate_openings(case)


def validate_values(case):
    for row in [*case.income, *case.tax_cash]:
        value = row.value
        if value.date > case.as_of or value.date.year > case.annual.policy.year:
            raise ValueError("Only observed income and tax cash may enter this credit case.")
        if value.currency == "USD" and value.usd_per_unit != 1:
            raise ValueError("USD facts require a unit USD conversion.")


def validate_openings(case):
    if any(r.origin_year >= case.annual.policy.year for r in case.opening_carries):
        raise ValueError("Opening carry vintages must precede this tax year.")
    credits = case.annual.foreign_credits
    if credits.regular or credits.alternative_minimum:
        raise ValueError("The baseline must exclude credits generated by this bridge.")
